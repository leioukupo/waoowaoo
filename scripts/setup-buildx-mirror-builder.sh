#!/bin/sh
# Create/refresh the docker-container buildx builder used by `docker compose build`
# on this machine: build steps run on the compose ffmpeg-mirror-net network so
# they can reach the ffmpeg-mirror container by name (default-bridge builds
# neither resolve names nor cross networks), and the buildkitd's Docker Hub
# pulls follow the daemon's registry mirrors (needed on LANs where Docker Hub
# is unreachable). Re-run after changing the daemon's mirror config.
#
# Usage: sh scripts/setup-buildx-mirror-builder.sh
set -eu
project_dir=$(cd "$(dirname "$0")/.." && pwd)
name=waoowaoo-bk
project=${COMPOSE_PROJECT_NAME:-$(basename "$project_dir")}
network="${project}_ffmpeg-mirror-net"

config=$(mktemp "${TMPDIR:-/tmp}/buildkitd.XXXXXX.toml")
trap 'rm -f "$config"' EXIT
python3 - "$config" <<'PYEOF'
import json, sys
try:
    with open('/etc/docker/daemon.json') as f:
        mirrors = json.load(f).get('registry-mirrors', [])
except Exception:
    mirrors = []
lines = ['# generated by scripts/setup-buildx-mirror-builder.sh from the Docker daemon config']
if mirrors:
    # Reorder the daemon's mirror list: most reliable first.
    order = ['docker.m.daocloud.io', 'docker.1ms.run', 'hub.rat.dev', 'docker.milu.moe']
    ranked = [m for m in order if any(m in x for x in mirrors)]
    ranked += [m for m in mirrors if m not in ranked]
    lines.append('[registry."docker.io"]')
    lines.append('  mirrors = [%s]' % ', '.join('"%s"' % m for m in ranked))
else:
    lines.append('# no registry-mirrors configured on the Docker daemon')
open(sys.argv[1], 'w').write('\n'.join(lines) + '\n')
PYEOF

if docker buildx inspect "$name" >/dev/null 2>&1; then
  docker buildx rm "$name"
fi
docker buildx create --name "$name" --driver docker-container \
  --driver-opt network="$network" \
  --buildkitd-config "$config" --bootstrap
docker buildx use "$name"
echo "builder '$name' active on network $network"
